#![allow(dead_code)]

use std::any::Any;
use std::collections::HashMap;

use serde_json::{Map, Value};

fn create_user(payload: Value) -> u64 {
    payload["id"].as_u64().unwrap_or(0)
}

fn load_settings() -> serde_json::Map<String, Value> {
    Map::new()
}

fn nested(items: Option<Vec<HashMap<String, Value>>>) -> Result<Box<Value>, std::io::Error> {
    drop(items);
    Ok(Box::new(Value::Null))
}

fn borrowed(_: &Value, raw: &mut Map<String, Value>) {
    raw.clear();
}

fn erased(state: Box<dyn Any + Send>) -> Option<&'static dyn Any> {
    drop(state);
    None
}

fn iterator() -> impl Iterator<Item = Value> {
    std::iter::empty()
}

async fn fetch() -> Value {
    Value::Null
}

type Json = Value;

fn aliased(value: Json) -> bool {
    value.is_null()
}

struct Event {
    name: String,
    payload: Value,
    tags: Vec<Value>,
}

struct Pair(u32, Option<Value>);

enum Message {
    Ping,
    Data { body: Value },
    Raw(Box<dyn Any>),
}

trait Handler {
    fn handle(&self, request: Value) -> Value;

    fn provided(&self, request: &Value) -> bool {
        request.is_object()
    }
}

struct Echo;

impl Echo {
    fn reply(&self, request: Value) -> Value {
        request
    }
}

// Not linted: the trait declaration owns the signature.
impl Handler for Echo {
    fn handle(&self, request: Value) -> Value {
        request
    }
}

// Not linted: typed data.
#[derive(serde::Deserialize)]
struct NewUser {
    name: String,
}

fn create_typed_user(payload: NewUser) -> String {
    payload.name
}

// Not linted: untyped values used only inside the body, not in the signature.
fn parse(input: &str) -> Result<NewUser, serde_json::Error> {
    let value: Value = serde_json::from_str(input)?;
    serde_json::from_value(value)
}

// Not linted: closures.
fn closures() {
    let check = |value: Value| value.is_null();
    check(Value::Null);
}

// Not linted: the `as_any` downcasting idiom.
trait Component {
    fn as_any(&self) -> &dyn Any;
    fn as_any_mut(&mut self) -> &mut dyn Any;
}

// Not linted: the std panic payload of `std::thread::Result`.
fn join(handle: std::thread::JoinHandle<u32>) -> std::thread::Result<u32> {
    handle.join()
}

// Not linted: `#[serde(flatten)]` catch-all for unknown keys.
#[derive(serde::Deserialize)]
struct Extensible {
    name: String,
    #[serde(flatten)]
    extra: HashMap<String, Value>,
}

// Not linted: other trait objects.
fn display(value: &dyn std::fmt::Display) -> String {
    value.to_string()
}

// Not linted: generated by a macro.
macro_rules! passthrough {
    () => {
        fn generated(value: Value) -> Value {
            value
        }
    };
}
passthrough!();

fn main() {}
