// Every report is an error: the reported attribute itself denies `warnings`,
// which includes this lint at the attribute's own location.
#![deny(warnings)]
#![cfg_attr(all(), deny(unused, warnings))]
// Not linted: denying specific lints or groups is a deliberate policy.
#![deny(unsafe_code, clippy::correctness)]
// Not linted: only affects doctests.
#![doc(test(attr(deny(warnings))))]
// Not linted: inactive `cfg_attr`.
#![cfg_attr(any(), deny(warnings))]

#[forbid(warnings)]
fn item_level() {}

// Not linted: a lint that merely contains the word.
#[deny(renamed_and_removed_lints)]
fn other_lint() {}

// Not linted: generated by a macro.
macro_rules! generated {
    () => {
        #[deny(warnings)]
        fn generated() {}
    };
}

generated!();

fn main() {
    item_level();
    other_lint();
    generated();
}
