// Crate-level suppression of an individual lint.
#![allow(dead_code)]
// Crate-level suppression of a group: reported once, as a group.
#![allow(unused)]
// Expanded from `cfg_attr`: still hand-written, so it is linted.
#![cfg_attr(all(), expect(clippy::needless_return, reason = "the crate prefers explicit returns"))]
// Not linted: `warn`, `deny` and `forbid` do not suppress anything.
#![warn(clippy::pedantic)]
// Not linted: inactive `cfg_attr`.
#![cfg_attr(any(), allow(missing_docs))]

mod inline_module {
    #![allow(clippy::module_name_repetitions, non_snake_case)]

    pub fn inline_module_value() -> u32 {
        1
    }
}

#[allow(clippy::all)]
fn outer_group() {}

#[expect(clippy::pedantic, reason = "the pedantic group is noisy here")]
fn outer_group_expect() {}

#[allow(clippy::complexity, clippy::cast_possible_truncation)]
fn mixed_group_and_lint(value: u64) -> u8 {
    value as u8
}

fn inner_group_in_body() {
    #![allow(nonstandard_style)]
    let CamelLocal = 1;
    let _ = CamelLocal;
}

// Not linted: a narrow outer suppression of a single lint on one item.
#[expect(clippy::cast_possible_truncation, reason = "value is masked to 0..=255 first")]
fn narrow(value: u64) -> u8 {
    (value & 0xff) as u8
}

// Not linted: an inner suppression of a single lint inside a function body
// only covers that function.
fn inner_single_lint_in_body() {
    #![allow(non_snake_case)]
    let CamelLocal = 1;
    let _ = CamelLocal;
}

// Known problem: `allow(warnings)` also silences this lint's own diagnostic.
#[allow(warnings)]
fn allow_warnings() {}

// Not linted: a lint whose name merely starts like a group.
#[allow(unused_variables)]
fn unused_variable() {
    let value = 1;
}

// Not linted: suppressions generated by a macro.
macro_rules! generated {
    () => {
        #[allow(clippy::all)]
        fn generated() {}
    };
}

generated!();

// Not linted: derives emit their own `#[allow(..)]` attributes.
#[derive(Debug, Clone, PartialEq)]
struct Derived(u32);

fn main() {
    outer_group();
    outer_group_expect();
    let _ = mixed_group_and_lint(1);
    inner_group_in_body();
    let _ = narrow(1);
    inner_single_lint_in_body();
    unused_variable();
    allow_warnings();
    generated();
    let _ = inline_module::inline_module_value();
    let _ = Derived(1).clone() == Derived(1);
}
