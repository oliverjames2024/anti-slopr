#![allow(dead_code, unused_macros)]

fn parse(input: &str) -> Result<u16, std::num::ParseIntError> {
    input.parse()
}

fn check_port(port: u16) {
    assert!(port > 0);
}

fn run_case(input: &str) {
    let port = parse(input).unwrap();
    check_port(port);
}

fn compute(input: &str) -> u16 {
    parse(input).unwrap_or(0)
}

#[test]
fn calls_without_checking() {
    let _port = compute("80");
}

#[test]
fn empty() {}

#[test]
fn prints_only() {
    println!("{}", compute("80"));
}

#[test]
fn returns_ok_without_question_mark() -> Result<(), std::num::ParseIntError> {
    let _ = compute("80");
    Ok(())
}

#[test]
fn ignores_result() {
    let _ = parse("80");
    let _ = parse("x").is_ok();
}

#[tokio::test]
async fn async_without_checking() {
    tokio::task::yield_now().await;
}

#[test]
#[ignore]
fn ignored_still_counts() {
    compute("80");
}

// Not linted: assertion macros, from std and with other names.
#[test]
fn asserts_eq() {
    assert_eq!(compute("80"), 80);
}

#[test]
fn asserts_matches() {
    assert!(matches!(parse("80"), Ok(80)));
}

#[test]
fn debug_asserts() {
    debug_assert_ne!(compute("80"), 0);
}

macro_rules! assert_port {
    ($port:expr) => {
        if $port == 0 {
            panic!("zero port");
        }
    };
}

#[test]
fn custom_assert_macro() {
    assert_port!(compute("80"));
}

#[test]
fn panics_on_mismatch() {
    if compute("80") != 80 {
        panic!("wrong port");
    }
}

#[test]
fn unreachable_branch() {
    match parse("80") {
        Ok(_) => {},
        Err(_) => unreachable!(),
    }
}

// Not linted: `unwrap`/`expect` on the result under test.
#[test]
fn unwraps() {
    parse("80").unwrap();
}

#[test]
fn expects() {
    parse("80").expect("valid port");
}

#[test]
fn unwraps_err() {
    parse("x").unwrap_err();
}

// Not linted: `?` in a test returning `Result`.
#[test]
fn question_mark() -> Result<(), std::num::ParseIntError> {
    parse("80")?;
    Ok(())
}

// Not linted: a test returning an `Err` it constructs.
#[test]
fn returns_err() -> Result<(), Box<dyn std::error::Error>> {
    if compute("80") != 80 {
        return Err("wrong port".into());
    }
    Ok(())
}

// Not linted: calls to assertion-named helpers.
#[test]
fn named_helper() {
    check_port(compute("80"));
}

struct Response(u16);

impl Response {
    fn assert_status(&self, status: u16) {
        assert_eq!(self.0, status);
    }
}

#[test]
fn named_method() {
    Response(200).assert_status(200);
}

// Not linted: a local helper that asserts internally.
#[test]
fn table_driven() {
    for input in ["80", "443"] {
        run_case(input);
    }
}

// Not linted: evidence inside a closure.
#[test]
fn in_closure() {
    ["80", "443"].iter().for_each(|input| assert_ne!(compute(input), 0));
}

// Not linted: `#[should_panic]` tests expect the panic.
#[test]
#[should_panic]
fn should_panic() {
    compute("80");
}

// Not linted: an async test that asserts.
#[tokio::test]
async fn async_asserts() {
    let value = tokio::task::spawn(async { 1 }).await.unwrap();
    assert_eq!(value, 1);
}

// Not linted: not a test.
fn helper_without_assertion() {
    compute("80");
}

// Not linted: test names generated by a macro.
macro_rules! smoke_tests {
    ($($name:ident),*) => {
        $(
            #[test]
            fn $name() {
                compute("80");
            }
        )*
    };
}

smoke_tests!(smoke_a, smoke_b);

